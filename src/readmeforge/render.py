"""Render evidence-based Markdown from a normalized project report."""

from __future__ import annotations

import html
import json
from typing import Any

from readmeforge import SCHEMA_VERSION
from readmeforge.errors import ReadmeForgeError


def validate_report(report: Any) -> dict[str, Any]:
    if not isinstance(report, dict):
        raise ReadmeForgeError("Repository report must be a JSON object.")
    if type(report.get("schema_version")) is not int or report.get("schema_version") != SCHEMA_VERSION:
        raise ReadmeForgeError(f"Unsupported report schema: {report.get('schema_version')!r}.")
    for key in ("project", "summary", "analysis"):
        if not isinstance(report.get(key), dict):
            raise ReadmeForgeError(f"Invalid report: {key} must be an object.")
    for key in ("files", "manifests", "top_level_directories", "top_level_files", "evidence", "warnings"):
        if not isinstance(report.get(key), list):
            raise ReadmeForgeError(f"Invalid report: {key} must be a list.")
    if not isinstance(report["project"].get("name"), str):
        raise ReadmeForgeError("Invalid report: project.name must be text.")
    return report


def _safe(value: Any, limit: int = 300) -> str:
    text = " ".join(str(value).replace("\r", " ").replace("\n", " ").split())
    return html.escape(text[:limit], quote=False).replace("|", "\\|")


def _code(value: Any) -> str:
    return _safe(value, 500).replace(chr(96), "'")


def _installation(report: dict[str, Any]) -> list[str]:
    project = report["project"]
    commands = report.get("install_commands", [])
    lines = [
        "## Installation", "",
        "Commands below were inferred from recognized manifests. Review the command and project instructions before running them.",
        "",
    ]
    if not commands:
        lines.extend([
            "No conventional package manifest was detected at the repository root. Review the project files and any existing documentation.",
            "",
        ])
        return lines
    for item in commands:
        lines.extend([
            f"### {_safe(item.get('label', 'Install'))}", "",
            "~~~bash", _code(item["command"]), "~~~", "",
            f"> {_safe(item.get('note', 'Inferred from local repository evidence.'), 400)}", "",
        ])
    if project.get("primary_language") == "Python":
        lines.extend([
            "For an isolated Python environment, create and activate a virtual environment before installing.", "",
            "**Windows PowerShell**", "", "~~~powershell",
            "python -m venv .venv", ".\\.venv\\Scripts\\Activate.ps1", "~~~", "",
            "**macOS / Linux**", "", "~~~bash",
            "python -m venv .venv", "source .venv/bin/activate", "~~~", "",
        ])
    return lines


def _architecture(report: dict[str, Any]) -> list[str]:
    name = _safe(report["project"]["name"], 100).replace('"', "'")
    directories = report.get("top_level_directories", [])[:10]
    lines = ["~~~mermaid", "flowchart TD", f'    R["{name} / repository root"]']
    index = 0
    if report.get("manifests"):
        index += 1
        lines.extend([f'    M{index}["Project manifests and configuration"]', f"    R --> M{index}"])
    for directory in directories:
        index += 1
        label = _safe(directory, 80).replace('"', "'")
        lines.extend([f'    D{index}["{label}/"]', f"    R --> D{index}"])
    if any(item["category"] == "test" for item in report["files"]):
        index += 1
        lines.extend([f'    T{index}["Test files and fixtures"]', f"    R --> T{index}"])
    if report.get("ci_paths"):
        index += 1
        lines.extend([f'    C{index}["CI configuration"]', f"    R --> C{index}"])
    if report.get("documentation_paths"):
        index += 1
        lines.extend([f'    X{index}["Documentation"]', f"    R --> X{index}"])
    if index == 0:
        lines.extend(['    F["Files inventoried from local tree"]', "    R --> F"])
    lines.extend([
        "~~~", "",
        "<sub>Generated from detected file layout. This is a repository map, not a runtime dependency graph.</sub>", "",
    ])
    return lines


def render_readme(report: dict[str, Any], *, title: str | None = None) -> str:
    validate_report(report)
    project = report["project"]
    summary = report["summary"]
    name = _safe(title or project["name"], 100)
    description = _safe(project.get("description") or f"Documentation for {name}.", 400)
    lines = [
        f"# {name}", "", description, "",
        "<!-- Generated by ReadmeForge from local repository evidence. Review and customize before publishing. -->",
        "",
        "> **Documentation status:** generated from repository structure and manifest evidence. Verify project behavior, commands, and license details before publishing.",
        "",
        "## Project snapshot", "",
        "| Signal | Detected evidence |", "|---|---|",
        f"| Primary language | {_safe(project.get('primary_language', 'Unknown'))} |",
        f"| Files inventoried | {summary.get('file_count', 0)} |",
        f"| Source files | {summary.get('source_file_count', 0)} |",
        f"| Test paths | {summary.get('test_path_count', 0)} |",
        f"| Additional documentation | {summary.get('documentation_file_count', 0)} |",
        f"| Project manifests | {summary.get('manifest_count', 0)} |",
        f"| CI configuration | {'Detected' if summary.get('has_ci') else 'Not detected'} |",
        f"| License file | {'Detected' if summary.get('has_license') else 'Not detected'} |",
        "",
        "These are file-system observations, not a quality score or proof that any test, command, or feature works.",
        "", "## Languages detected", "",
    ]
    languages = project.get("languages", [])
    if languages:
        lines.extend(["| Language | Files |", "|---|---:|"])
        for language in languages[:12]:
            lines.append(f"| {_safe(language['name'], 60)} | {int(language['file_count'])} |")
    else:
        lines.append("No recognized language extensions were detected.")
    lines.extend(["", "## Repository signals", ""])
    if report.get("evidence"):
        lines.extend(f"- {_safe(item, 400)}" for item in report["evidence"][:12])
    else:
        lines.append("No conventional project signals were detected. Add manifests, tests, and documentation where appropriate.")
    lines.extend(["", "## Quick start", ""])
    lines.extend(_installation(report))
    lines.extend(["## Usage", ""])
    commands = report.get("run_commands", [])
    if commands:
        lines.extend([
            "Commands below were inferred from manifest scripts. Confirm their definitions before executing them.",
            "", "| Detected command | Manifest definition |", "|---|---|",
        ])
        for item in commands[:16]:
            lines.append(f"| <code>{_code(item['command'])}</code> | <code>{_code(item.get('definition', ''))}</code> |")
        lines.append("")
    else:
        lines.extend([
            "No conventional start or CLI command was detected in supported root manifests. Add a verified command once the intended entry point is known.",
            "",
        ])
    node_scripts = project.get("package_scripts", {}).get("node", {})
    if node_scripts:
        manager = "pnpm" if "pnpm-lock.yaml" in report["manifests"] else ("yarn" if "yarn.lock" in report["manifests"] else "npm")
        lines.extend(["### Package scripts", "", "| Script | Command |", "|---|---|"])
        for script_name in sorted(node_scripts)[:16]:
            lines.append(f"| {_safe(script_name, 80)} | <code>{manager} run {_code(script_name)}</code> |")
        lines.append("")
    lines.extend(["## Testing", ""])
    tests = report.get("test_commands", [])
    if tests:
        lines.extend([
            "These commands were inferred from test paths or manifest scripts. ReadmeForge has not run them against the inspected project.",
            "",
        ])
        for item in tests[:8]:
            lines.extend([
                f"### {_safe(item.get('label', 'Test command'), 80)}", "",
                "~~~bash", _code(item["command"]), "~~~", "",
            ])
            if item.get("note"):
                lines.extend([f"> {_safe(item['note'], 300)}", ""])
    else:
        lines.extend([
            "No conventional test directory or supported test script was detected. Document a verified test command when available.",
            "",
        ])
    lines.extend(["## Detected repository structure", ""])
    if report.get("top_level_directories") or report.get("top_level_files"):
        lines.extend(_architecture(report))
        lines.extend(["### Top-level directories", ""])
        lines.extend(f"- <code>{_code(item)}/</code>" for item in report["top_level_directories"][:24])
        if not report.get("top_level_directories"):
            lines.append("No top-level directories were detected.")
        lines.append("")
        if report.get("top_level_files"):
            lines.extend(["### Important root files", ""])
            lines.extend(f"- <code>{_code(item)}</code>" for item in report["top_level_files"][:24])
            lines.append("")
    lines.extend([
        "## Contributing", "",
        "1. Create a focused branch for your change.",
        "2. Add or update tests and documentation for behavior changes.",
        "3. Run the project's verified lint, formatting, and test commands before opening a pull request.",
        "4. Explain the reason for the change, expected behavior, and compatibility implications.",
        "",
        "Follow the repository's contributing guide if one exists. Never include secrets, access tokens, production data, or private source in public issues and fixtures.",
        "", "## Security and limitations", "",
        "- Repository facts were inferred from local file paths and selected manifest metadata.",
        "- Detected commands are suggestions, not proof that a program runs successfully.",
        "- Review the impact of installing dependencies or running scripts from unfamiliar repositories.",
        "- Check license and dependency obligations before redistributing this project.", "",
    ])
    licenses = report.get("license_paths", [])
    if licenses:
        lines.append(f"License file detected: <code>{_code(licenses[0])}</code>. Review the license text to confirm its terms.")
    else:
        lines.append("No conventional license file was detected. Verify and add a license before accepting external contributions or redistributing.")
    lines.extend([
        "", "---", "",
        "<sub>Generated with ReadmeForge by VerityAgent. Maintainers remain responsible for accuracy.</sub>", "",
    ])
    return "\n".join(lines)


def render_json_report(report: dict[str, Any]) -> str:
    validate_report(report)
    return json.dumps(report, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
