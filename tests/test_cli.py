from __future__ import annotations

import contextlib
import io
import tempfile
import unittest
from pathlib import Path

from readmeforge.cli import main


class CLITests(unittest.TestCase):
    def invoke(self, args: list[str]) -> tuple[int, str, str]:
        stdout = io.StringIO()
        stderr = io.StringIO()
        with contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
            result = main(args)
        return result, stdout.getvalue(), stderr.getvalue()

    def test_version(self) -> None:
        code, stdout, stderr = self.invoke(["--version"])
        self.assertEqual(code, 0)
        self.assertIn("ReadmeForge 0.1.0", stdout)
        self.assertEqual(stderr, "")

    def test_generate_writes_a_readme(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            (root / "pyproject.toml").write_text('[project]\nname = "test-app"\n', encoding="utf-8")
            (root / "main.py").write_text("value = 1\n", encoding="utf-8")
            output = root / "README.generated.md"
            code, stdout, stderr = self.invoke(["generate", str(root), "--output", str(output)])
            self.assertEqual((code, stderr), (0, ""), stdout + stderr)
            self.assertIn("# test-app", output.read_text(encoding="utf-8"))

    def test_does_not_overwrite_without_force(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            output = root / "README.md"
            output.write_text("human-authored content", encoding="utf-8")
            code, _, stderr = self.invoke(["generate", str(root), "--output", str(output)])
            self.assertEqual(code, 2)
            self.assertIn("Use --force", stderr)
            self.assertEqual(output.read_text(encoding="utf-8"), "human-authored content")
            code, _, stderr = self.invoke(["generate", str(root), "--output", str(output), "--force"])
            self.assertEqual((code, stderr), (0, ""))
            self.assertIn("Generated by ReadmeForge", output.read_text(encoding="utf-8"))

    def test_check_missing_then_current_readme(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            (root / "pyproject.toml").write_text('[project]\nname = "check-app"\n', encoding="utf-8")
            code, stdout, _ = self.invoke(["check", str(root)])
            self.assertEqual(code, 1)
            self.assertIn("missing", stdout.lower())
            output = root / "README.md"
            self.invoke(["generate", str(root), "--output", str(output)])
            code, stdout, _ = self.invoke(["check", str(root)])
            self.assertEqual(code, 0)
            self.assertIn("up to date", stdout)

    def test_inspect_json_output(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            (root / "app.ts").write_text("const value = 1;\n", encoding="utf-8")
            code, stdout, stderr = self.invoke(["inspect", str(root), "--format", "json"])
        self.assertEqual((code, stderr), (0, ""))
        self.assertIn('"schema_version": 1', stdout)
        self.assertIn('"TypeScript"', stdout)

    def test_invalid_repository_has_clean_error(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            code, stdout, stderr = self.invoke(["inspect", str(Path(directory) / "missing")])
        self.assertEqual(code, 2)
        self.assertEqual(stdout, "")
        self.assertIn("cannot be resolved", stderr.lower())
        self.assertNotIn("Traceback", stderr)


if __name__ == "__main__":
    unittest.main()
